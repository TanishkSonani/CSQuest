import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {randomUUID} from 'node:crypto';
import {readJson,atomicJson} from '../../../src/platform/io.mjs';
const courseRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
function evidence(transcript,anchors){
 const ranked=transcript.segments.map(s=>({...s,score:anchors.reduce((n,a)=>n+(s.text.toLowerCase().includes(a.toLowerCase())?1:0),0)})).filter(s=>s.score>0).sort((a,b)=>b.score-a.score||a.start-b.start);
 const selected=[];for(const s of ranked){if(selected.every(p=>Math.abs(p.start-s.start)>45)){selected.push(s);if(selected.length===2)break;}}
 return selected.sort((a,b)=>a.start-b.start).map(s=>({start:s.start,end:s.end,text:s.text.trim()}));
}
export async function buildReviewed(base=courseRoot){
 const stamp=await fs.stat(new URL('./authored-lectures.mjs',import.meta.url));
 const authored=await import('./authored-lectures.mjs?version='+stamp.mtimeMs);
 const additionsStamp=await fs.stat(new URL('./adder-decoder-lessons.mjs',import.meta.url));
 const {adderDecoderLectures}=await import('./adder-decoder-lessons.mjs?version='+additionsStamp.mtimeMs);
 const flipStamp=await fs.stat(new URL('./flipflop-lessons.mjs',import.meta.url));
 const {flipflopLectures}=await import('./flipflop-lessons.mjs?version='+flipStamp.mtimeMs);
 const authoredLectures=new Map([...authored.authoredLectures,...adderDecoderLectures,...flipflopLectures]);
 const reviewed=[],coverage=[],missing=[];
 const files=(await fs.readdir(path.join(base,'data','transcripts'))).filter(f=>/^\d+\.json$/.test(f)).sort((a,b)=>parseInt(a)-parseInt(b));
 for(const file of files){
  const transcript=JSON.parse(await fs.readFile(path.join(base,'data','transcripts',file),'utf8'));
  if(!transcript.sourceCompletedAt||!transcript.segments?.length)continue;
  const definition=authoredLectures.get(transcript.id);
  if(!definition){missing.push({id:transcript.id,title:transcript.title});continue;}
  const stages=definition.stages.map((s,part)=>{
   const references=evidence(transcript,s.anchors);
   if(!references.length)throw new Error(`Lecture ${transcript.id}, ${s.title}: no matching transcript evidence`);
   if(s.questions.length!==4)throw new Error(`Lecture ${transcript.id} stage ${part}: expected four exercises`);
   const questions=s.questions.map((q,i)=>{if(q.type!=='choice')return q;const shift=(transcript.id+part+i)%q.options.length;return {...q,options:[...q.options.slice(shift),...q.options.slice(0,shift)],answer:(q.answer-shift+q.options.length)%q.options.length};});
   return {id:transcript.id*3+part,lecture:transcript.id,title:s.title,lectureTitle:definition.label,start:references[0].start,concept:definition.intro,teachingSteps:s.steps,anchors:s.anchors,questions,minutes:4,ready:true,contentStatus:'Lecture-specific teaching reviewed against completed machine transcript',contentVersion:2,sourceFile:transcript.file,sourceReferences:references,excerpt:references[0].text};
  });
  reviewed.push(...stages);coverage.push({lecture:transcript.id,title:transcript.title,lessonIds:stages.map(s=>s.id),questions:12,sourceCompletedAt:transcript.sourceCompletedAt});
 }
 await fs.mkdir(path.join(base,'content'),{recursive:true});
 const text='// Generated by authoring/build-reviewed.mjs from authored teaching and completed transcripts.\nexport const reviewedLessons='+JSON.stringify(reviewed,null,2)+';\n';
 const target=path.join(base,'content','reviewed-lessons.js');let old='';try{old=await fs.readFile(target,'utf8');}catch{}
 if(old!==text){const temporary=target+'.'+randomUUID()+'.tmp';await fs.writeFile(temporary,text);await fs.rename(temporary,target);}
 const reportFile=path.join(base,'data','lesson-build.json');
 const previous=await readJson(reportFile);
 const {builtAt,...previousCoverage}=previous||{};
 const reportData={reviewedLectures:coverage.length,reviewedLevels:reviewed.length,questions:reviewed.length*4,coverage,awaitingEditorialReview:missing};
 const unchanged=old===text&&JSON.stringify(previousCoverage)===JSON.stringify(reportData);
 const report={builtAt:unchanged?builtAt:new Date().toISOString(),...reportData};
 if(!unchanged)await atomicJson(reportFile,report);
 return {lessons:reviewed,report};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){const {report}=await buildReviewed();console.log(JSON.stringify({reviewedLectures:report.reviewedLectures,reviewedLevels:report.reviewedLevels,questions:report.questions,awaitingEditorialReview:report.awaitingEditorialReview}));}
